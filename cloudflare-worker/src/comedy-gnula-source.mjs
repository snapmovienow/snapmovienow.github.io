const MEDIA_HOSTS = new Set(['s14-s1001604.97bf1.com', 's13-s501740.s1q2105.com', 's7-5042yyg.s1q2105.com']);
const fail = () => { throw Error('comedy_source_unavailable'); };
function safe(value) {
 if (typeof value !== 'string' || value.length > 12000 || /[\\\u0000-\u0020]/.test(value) || /\/(?:\.\.?)(?:\/|[?#]|$)/.test(value) || /%(?:2e|2f|5c)/i.test(value.split(/[?#]/, 1)[0])) fail();
 let u; try { u = new URL(value); } catch { fail(); }
 if (u.protocol !== 'https:' || u.username || u.password || u.port || u.href.includes('#') || /%(?:2e|2f|5c)/i.test(u.pathname)) fail();
 return u;
}
function definition(value) {
 try { const u = safe(value instanceof URL ? value.href : value); return DEFINITIONS.find(d => d.page === u.href) || null; }
 catch { return null; }
}
export const COMEDY_GNULA_EPISODES = Object.freeze(DEFINITIONS.map(d => Object.freeze({...d})));
export const isComedyGnulaPage = value => !!definition(value);
const prefixPattern = /^\/hls\/[A-Za-z0-9]{20,60}\/$/;
const tokenPattern = /^[A-Za-z0-9:_-]{1,700}$/;
function validContext(page, context) {
 const d = definition(page);
 return d && context && context.provider === 'vidara' && context.page === d.page && context.season === d.season && context.episode === d.episode && context.embed === d.embed && context.host && MEDIA_HOSTS.has(context.host) && prefixPattern.test(context.prefix || '') && tokenPattern.test(context.token || '') ? d : null;
}
export function comedyGnulaMediaAllowed(page, value, context = {}) {
 try {
  const u = safe(value instanceof URL ? value.href : value);
  if (!validContext(page, context) || u.hostname !== context.host || !u.pathname.startsWith(context.prefix)) return false;
  const file = u.pathname.slice(context.prefix.length);
  if (!/^(?:master\.m3u8|index_\d{2,4}x\d{2,4}\.m3u8|seg_\d{2,4}x\d{2,4}_\d{3,8}\.(?:woff2?|css|js))$/.test(file)) return false;
  return [...u.searchParams.keys()].join(',') === 'token' && u.searchParams.get('token') === context.token;
 } catch { return false; }
}
export function comedyGnulaMediaHeaders(page, context = {}) {
 if (!validContext(page, context)) fail();
 const embed = new URL(context.embed);
 return {Referer: embed.origin + '/', Origin: embed.origin};
}
async function textResponse(response, max) {
 if (!response.ok || Number(response.headers.get('content-length')) > max) { await response.body?.cancel(); fail(); }
 const reader = response.body?.getReader(); if (!reader) fail();
 let size = 0, text = ''; const decoder = new TextDecoder();
 try {
  for (;;) { const {value, done} = await reader.read(); if (done) break; size += value.byteLength; if (size > max) fail(); text += decoder.decode(value, {stream: true}); }
  return text + decoder.decode();
 } finally { await reader.cancel().catch(() => {}); reader.releaseLock(); }
}
async function read(value, allowed, {fetcher, signal, headers = {}, body}, max = 1000000) {
 let u = safe(value);
 for (let hop = 0; hop < 3; hop++) {
  if (signal?.aborted) throw signal.reason;
  if (!allowed(u)) fail();
  const response = await fetcher(u.href, {method: body === undefined ? 'GET' : 'POST', headers: {'User-Agent': 'Mozilla/5.0', ...headers}, ...(body === undefined ? {} : {body}), redirect: 'manual', signal});
  if (response.status < 300 || response.status >= 400) return textResponse(response, max);
  // A POST redirect would alter the observed public protocol. Never replay a
  // config body elsewhere or follow a redirect outside its reviewed endpoint.
  const location = response.headers.get('location'); await response.body?.cancel();
  if (body !== undefined || !location || hop === 2) fail();
  u = safe(new URL(location, u).href);
 }
 fail();
}
function hls(text, page, base, context) {
 if (!text.trimStart().startsWith('#EXTM3U') || /KEYFORMAT=|METHOD=SAMPLE-AES|#EXT-X-SESSION-KEY:/i.test(text)) fail();
 const resources = text.split(/\r?\n/).map(x => x.trim()).filter(x => x && !x.startsWith('#'));
 for (const m of text.matchAll(/\bURI="([^"\r\n]+)"/g)) resources.push(m[1]);
 if (!resources.length || resources.some(value => !comedyGnulaMediaAllowed(page, new URL(value, base), context))) fail();
 return resources;
}
function sourceTitleMatches(title, d) {
 if (typeof title !== 'string' || title.length > 300) return false;
 const match = title.match(/^([A-Za-z0-9+/=]+)\.(\d+)x(\d+)\.CAST(?:\.|$)/);
 if (!match || Number(match[2]) !== d.season || Number(match[3]) !== d.episode) return false;
 try { return /^Muertos\s+S\.L\.\.20\d{2}$/.test(atob(match[1])); } catch { return false; }
}
export async function resolveComedyGnula(page, {fetcher = fetch, signal} = {}) {
 const d = definition(page); if (!d) fail();
 const options = {fetcher, signal: signal ? AbortSignal.any([signal, AbortSignal.timeout(45000)]) : AbortSignal.timeout(45000)};
 const embed = safe(d.embed);
 const html = await read(embed.href, u => u.href === embed.href, {...options, headers: {Referer: d.page}});
 // This is the ordinary player config request. An empty advanced-codec list
 // selects the player's baseline AVC rendition. No fingerprint, guard headers,
 // account credentials, challenge code, or page scripts are evaluated.
 if (!html.includes('apiURL="/api/stream"') || !html.includes('filecode:filecode,device:detectDevice(),codecs:cs')) fail();
 const api = new URL('/api/stream', embed);
 const raw = await read(api.href, u => u.href === api.href, {...options, headers: {'Content-Type': 'application/json', Accept: 'application/json', Referer: embed.href}, body: JSON.stringify({filecode: embed.pathname.split('/').pop(), device: 'web', codecs: []})}, 250000);
 let payload; try { payload = JSON.parse(raw); } catch { fail(); }
 // External VAST must be implemented in the client before admitting a source
 // that requests it. HLS content and its ad markers are never stripped.
 if (!sourceTitleMatches(payload.title, d) || payload.vast_ads || payload.drm || payload.filecode !== embed.pathname.split('/').pop()) fail();
 const url = safe(payload.streaming_url), prefix = url.pathname.slice(0, url.pathname.lastIndexOf('/') + 1);
 const context = {provider: 'vidara', page: d.page, season: d.season, episode: d.episode, embed: d.embed, host: url.hostname, prefix, token: url.searchParams.get('token')};
 if (!validContext(d.page, context) || !comedyGnulaMediaAllowed(d.page, url, context) || !url.pathname.endsWith('/master.m3u8')) fail();
 const master = await read(url.href, u => comedyGnulaMediaAllowed(d.page, u, context), {...options, headers: comedyGnulaMediaHeaders(d.page, context)});
 hls(master, d.page, url, context);
 return {url: url.href, context};
}
